"""Cloud-only install (#70 b): oxc (controller + cloud gateway) without a local engine.

    python -m snapdragon_ai_lab.cloud_install --cloud-only --prefix ~/oxc --config-dir ~/oxc/config \
        --models-file models.json --daily-budget 2

Works on any Linux (x86_64 or arm64). It never builds an engine, downloads a model or looks for
Snapdragon/Hexagon/NPU hardware; it imports none of the bootstrap_* modules. It writes only under
--prefix, --config-dir and (unless --no-systemd) --unit-dir. API keys are never written: put them
in <config-dir>/cloud-secrets.json (mode 0600), see docs/CLOUD-MODELS.md.
"""
import argparse
import copy
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys

RUNTIME = Path(__file__).resolve().parent / 'runtime'
UNIT_NAME = re.compile(r'[A-Za-z0-9_.@-]{1,64}')


def _anthropic(name, output, price_in, price_out):
    return {'kind': 'remote/anthropic', 'provider': 'anthropic', 'base_url': 'https://api.anthropic.com',
            'upstream_model': name, 'context_window': 200000, 'max_output': output,
            'pricing': {'input_per_million': price_in, 'output_per_million': price_out}}


def _openai(name, output, price_in, price_out):
    return {'kind': 'remote/openai', 'provider': 'openai', 'base_url': 'https://api.openai.com/v1',
            'upstream_model': name, 'context_window': 200000, 'max_output': output,
            'pricing': {'input_per_million': price_in, 'output_per_million': price_out}}


def _openrouter(name, output, price_in, price_out):
    return {'kind': 'remote/openrouter', 'provider': 'openrouter', 'base_url': 'https://openrouter.ai/api/v1',
            'upstream_model': name, 'context_window': 200000, 'max_output': output,
            'pricing': {'input_per_million': price_in, 'output_per_million': price_out}}


# Used when --models-file is absent: the owner's catalog (id, upstream model, context, max output,
# USD per million input/output tokens). Review prices before relying on the daily budget.
DEFAULT_MODELS = {
    'anthropic/claude-haiku-5-5': _anthropic('claude-haiku-5-5', 32000, 0.5, 2.5),
    'anthropic/claude-sonnet-5-5': _anthropic('claude-sonnet-5-5', 32000, 2.0, 10.0),
    'anthropic/claude-opus-5-5': _anthropic('claude-opus-5-5', 32000, 4.0, 20.0),
    'openai/gpt-6-luna': _openai('gpt-6-luna', 128000, 0.1, 0.5),
    'openai/gpt-6.1-sol': _openai('gpt-6.1-sol', 128000, 2.0, 10.0),
    'openrouter/deepseek-v4-pro': _openrouter('deepseek/deepseek-v4-pro-0813', 32768, 0.111, 4.44),
    'openrouter/deepseek-v4.1-flash': _openrouter('deepseek/deepseek-v4.1-flash', 32768, 0.0507, 0.2028),
}


class InstallError(Exception):
    pass


def load_models(path):
    """The catalog from a JSON file, validated with the gateway's own rules (no network)."""
    from .runtime import cloud
    if path is None:
        models = copy.deepcopy(DEFAULT_MODELS)
        for alias, raw in models.items():
            if cloud.entry(alias, raw) is None:
                raise InstallError(f'Built-in catalog entry {alias!r} is invalid.')
        return models
    try:
        models = json.loads(Path(path).read_text())
    except (OSError, ValueError):
        raise InstallError('The models file is missing or not valid JSON.') from None
    if not isinstance(models, dict):
        raise InstallError('The models file must be a JSON object of catalog entries.')
    for alias, raw in models.items():
        if cloud.entry(alias, raw) is None:
            raise InstallError(f'Catalog entry {alias!r} is not valid (see docs/CLOUD-MODELS.md).')
    return models


def copy_runtime(destination):
    destination.mkdir(parents=True, exist_ok=True)
    for source in sorted(RUNTIME.glob('*.py')):
        shutil.copy2(source, destination / source.name)


def launcher(prefix, config, port):
    state = prefix / 'state'
    env = {'LOCAL_LLM_CONFIG': config / 'runtime.json', 'LOCAL_LLM_PORT': port,
           'LOCAL_AI_LEASE': state / 'inference.lock', 'LOCAL_AI_LEDGER_DIR': state / 'ledger',
           'XDG_STATE_HOME': state, 'PYTHONDONTWRITEBYTECODE': 1}
    lines = ['#!/bin/sh', '# oxc cloud-only controller (generated by cloud_install)']
    lines += [f'export {k}={shlex.quote(str(v))}' for k, v in env.items()]
    lines.append(f'exec {shlex.quote(sys.executable)} {shlex.quote(str(prefix / "share/oxc/runtime/controller.py"))} "$@"')
    return '\n'.join(lines) + '\n'


def unit(name, script, prefix):
    return ('[Unit]\nDescription=oxc cloud-only controller (%s)\n[Service]\nType=simple\n'
            'ExecStart=%s\nWorkingDirectory=%s\nRestart=on-failure\nRestartSec=5\nUMask=0077\nLimitCORE=0\n'
            '[Install]\nWantedBy=default.target\n') % (name, script, prefix)


def install(args, runner=subprocess.run):
    if not UNIT_NAME.fullmatch(args.unit_name):
        raise InstallError('Invalid unit name.')
    if not 1 <= args.port <= 65535:
        raise InstallError('Invalid port.')
    if not args.daily_budget > 0:
        raise InstallError('The daily budget must be a positive USD amount.')
    prefix, config = Path(args.prefix).absolute(), Path(args.config_dir).absolute()
    models = load_models(args.models_file)
    runtime_json = config / 'runtime.json'
    if runtime_json.exists() and not args.force:
        raise InstallError('runtime.json already exists in the config directory; it was kept (use --force to replace).')
    value = {'cloud_only': True, 'cloud': {'enabled': True, 'daily_budget_usd': args.daily_budget,
                                           'secrets_file': str(config / 'cloud-secrets.json'), 'models': models}}
    config.mkdir(parents=True, exist_ok=True, mode=0o700)
    runtime_json.write_text(json.dumps(value, indent=2) + '\n')
    os.chmod(runtime_json, 0o600)
    copy_runtime(prefix / 'share/oxc/runtime')
    (prefix / 'bin').mkdir(parents=True, exist_ok=True)
    script = prefix / 'bin/oxc-controller'
    script.write_text(launcher(prefix, config, args.port))
    os.chmod(script, 0o755)
    if args.oxa_binary:
        shutil.copy2(args.oxa_binary, prefix / 'bin/oxa')
    result = {'next_step': f"put your API keys in {config / 'cloud-secrets.json'} (mode 0600), "
                           'then `curl <api_base>/models`; the file is never read or printed here',
              'prefix': str(prefix), 'runtime_json': str(runtime_json), 'launcher': str(script),
              'models': len(models), 'api_base': f'http://127.0.0.1:{args.port}/v1',
              'secrets_file': str(config / 'cloud-secrets.json')}
    if args.no_systemd:
        result['run'] = str(script)
        return result
    unit_dir = Path(args.unit_dir).absolute() if args.unit_dir else Path(
        os.environ.get('XDG_CONFIG_HOME') or Path.home() / '.config') / 'systemd/user'
    unit_dir.mkdir(parents=True, exist_ok=True)
    (unit_dir / f'{args.unit_name}.service').write_text(unit(args.unit_name, script, prefix))
    runner(['systemctl', '--user', 'daemon-reload'], check=True)
    runner(['systemctl', '--user', 'enable', '--now', f'{args.unit_name}.service'], check=True)
    result['unit'] = f'{args.unit_name}.service'
    return result


def main(argv=None, runner=subprocess.run):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--cloud-only', action='store_true', required=True,
                        help='no local engine, no model download, no Snapdragon steps (the only mode here)')
    parser.add_argument('--prefix', required=True, help='install root (bin/, share/oxc/, state/)')
    parser.add_argument('--config-dir', required=True, help='holds runtime.json and cloud-secrets.json')
    parser.add_argument('--port', type=int, default=8092)
    parser.add_argument('--unit-name', default='oxc')
    parser.add_argument('--unit-dir', help='default: ~/.config/systemd/user')
    parser.add_argument('--no-systemd', action='store_true', help='write no unit; run bin/oxc-controller in the foreground')
    parser.add_argument('--models-file', help='JSON object of remote catalog entries (docs/CLOUD-MODELS.md); default: built-in catalog')
    parser.add_argument('--daily-budget', type=float, default=1.0, help='USD per day (default 1.0)')
    parser.add_argument('--oxa-binary', help='copy this built oxa binary to <prefix>/bin/oxa')
    parser.add_argument('--force', action='store_true', help='replace an existing runtime.json')
    args = parser.parse_args(argv)
    try:
        result = install(args, runner)
    except InstallError as error:
        print('cloud-install: ' + str(error), file=sys.stderr)
        return 1
    except (OSError, subprocess.SubprocessError) as error:
        print('cloud-install: ' + type(error).__name__, file=sys.stderr)
        return 1
    print(json.dumps(result, indent=2))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
